-- Only active signed-in profiles explicitly marked as administrators may write settings.
alter table public.app_home_settings enable row level security;
drop policy if exists app_home_settings_admin_write on public.app_home_settings;
drop policy if exists app_home_settings_admin_insert on public.app_home_settings;
drop policy if exists app_home_settings_admin_update on public.app_home_settings;
create policy app_home_settings_admin_insert
  on public.app_home_settings for insert to authenticated
  with check (exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and lower(coalesce(p.role, '')) in ('admin', 'super_admin', 'owner', 'editor', 'moderator', 'media_manager', 'shop_manager')
      and coalesce(p.is_suspended, false) = false
  ));
create policy app_home_settings_admin_update
  on public.app_home_settings for update to authenticated
  using (exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and lower(coalesce(p.role, '')) in ('admin', 'super_admin', 'owner', 'editor', 'moderator', 'media_manager', 'shop_manager')
      and coalesce(p.is_suspended, false) = false
  ))
  with check (exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and lower(coalesce(p.role, '')) in ('admin', 'super_admin', 'owner', 'editor', 'moderator', 'media_manager', 'shop_manager')
      and coalesce(p.is_suspended, false) = false
  ));

-- Public read remains available; no public write policy is created.
grant select on public.countries to anon, authenticated;
grant select, insert, update on public.app_home_settings to authenticated;
